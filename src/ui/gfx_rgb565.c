void gfx_clear(gfx_fb_t *fb, uint16_t color)
{
    for (size_t i = 0; i < GFX_FB_PIXELS; ++i) {
        fb->pixels[i] = color;
    }
}

void gfx_draw_pixel(gfx_fb_t *fb, int x, int y, uint16_t color)
{
    if (x < 0 || x >= GFX_WIDTH || y < 0 || y >= GFX_HEIGHT) {
        return;
    }
    fb->pixels[(size_t)y * GFX_WIDTH + (size_t)x] = color;
}

void gfx_draw_hline(gfx_fb_t *fb, int x, int y, int w, uint16_t color)
{
    if (y < 0 || y >= GFX_HEIGHT || w <= 0) {
        return;
    }
    int x0 = x < 0 ? 0 : x;
    int x1 = x + w;
    if (x1 > GFX_WIDTH) {
        x1 = GFX_WIDTH;
    }
    uint16_t *row = &fb->pixels[(size_t)y * GFX_WIDTH];
    for (int px = x0; px < x1; ++px) {
        row[px] = color;
    }
}

void gfx_draw_vline(gfx_fb_t *fb, int x, int y, int h, uint16_t color)
{
    if (x < 0 || x >= GFX_WIDTH || h <= 0) {
        return;
    }
    int y0 = y < 0 ? 0 : y;
    int y1 = y + h;
    if (y1 > GFX_HEIGHT) {
        y1 = GFX_HEIGHT;
    }
    for (int py = y0; py < y1; ++py) {
        fb->pixels[(size_t)py * GFX_WIDTH + (size_t)x] = color;
    }
}

void gfx_fill_rect(gfx_fb_t *fb, int x, int y, int w, int h, uint16_t color)
{
    if (w <= 0 || h <= 0) {
        return;
    }
    int y0 = y < 0 ? 0 : y;
    int y1 = y + h;
    if (y1 > GFX_HEIGHT) {
        y1 = GFX_HEIGHT;
    }
    for (int py = y0; py < y1; ++py) {
        gfx_draw_hline(fb, x, py, w, color);
    }
}

void gfx_draw_rect(gfx_fb_t *fb, int x, int y, int w, int h, uint16_t color)
{
    if (w <= 0 || h <= 0) {
        return;
    }
    gfx_draw_hline(fb, x, y, w, color);
    gfx_draw_hline(fb, x, y + h - 1, w, color);
    gfx_draw_vline(fb, x, y, h, color);
    gfx_draw_vline(fb, x + w - 1, y, h, color);
}

void gfx_fill_round_rect(gfx_fb_t *fb, int x, int y, int w, int h, uint16_t color)
{
    if (w < 3 || h < 3) {
        gfx_fill_rect(fb, x, y, w, h, color);
        return;
    }
    gfx_draw_hline(fb, x + 1, y, w - 2, color);
    gfx_fill_rect(fb, x, y + 1, w, h - 2, color);
    gfx_draw_hline(fb, x + 1, y + h - 1, w - 2, color);
}

void gfx_draw_char(gfx_fb_t *fb, int x, int y, char c, uint16_t fg, uint16_t bg,
                   bool opaque_bg, int scale)
{
    if (scale < 1) {
        scale = 1;
    }
    unsigned char uc = (unsigned char)c;
    if (uc < 0x20 || uc > 0x7E) {
        uc = '?';
    }
    const uint8_t *glyph = s_font5x7[uc - 0x20];

    for (int col = 0; col < 5; ++col) {
        uint8_t bits = glyph[col];
        for (int row = 0; row < 8; ++row) {
            bool on = (bits >> row) & 0x01;
            if (on || opaque_bg) {
                uint16_t color = on ? fg : bg;
                if (scale == 1) {
                    gfx_draw_pixel(fb, x + col, y + row, color);
                } else {
                    gfx_fill_rect(fb, x + col * scale, y + row * scale,
                                  scale, scale, color);
                }
            }
        }
    }
    if (opaque_bg) {
        gfx_fill_rect(fb, x + 5 * scale, y, scale, 8 * scale, bg);
    }
}

void gfx_draw_text(gfx_fb_t *fb, int x, int y, const char *str, uint16_t fg,
                   uint16_t bg, bool opaque_bg, int scale)
{
    if (!str) {
        return;
    }
    if (scale < 1) {
        scale = 1;
    }
    int cursor_x = x;
    int advance = 6 * scale;
    while (*str) {
        if (cursor_x >= GFX_WIDTH) {
            break;
        }
        gfx_draw_char(fb, cursor_x, y, *str, fg, bg, opaque_bg, scale);
        cursor_x += advance;
        ++str;
    }
}

int gfx_text_width(const char *str, int scale)
{
    if (!str || !*str) {
        return 0;
    }
    if (scale < 1) {
        scale = 1;
    }
    size_t len = strlen(str);
    return (int)(len * 6U * (size_t)scale - (size_t)scale);
}
